-- Etapa 3 (Fundação): contas e espaço Minha Vida (RF01, RF03).
create table pessoa (
    id          bigint generated by default as identity primary key,
    nome        varchar(120) not null,
    email       varchar(254) not null,
    senha_hash  varchar(100) not null,
    criada_em   timestamp    not null,
    constraint uk_pessoa_email unique (email)
);

create table minha_vida (
    id          bigint generated by default as identity primary key,
    pessoa_id   bigint    not null references pessoa (id),
    criada_em   timestamp not null,
    constraint uk_minha_vida_pessoa unique (pessoa_id)
);
