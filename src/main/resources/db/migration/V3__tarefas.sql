-- Sprint 4.2: Tarefas (RF05, RF07). Prazo obrigatório; responsável padrão = criador.
create table tarefa (
    id               bigint generated by default as identity primary key,
    area_id          bigint        not null references area (id),
    titulo           varchar(120)  not null,
    descricao        varchar(1000),
    prazo            timestamp     not null,
    prioridade       varchar(10)   not null,
    status           varchar(12)   not null,
    criador_id       bigint        not null references pessoa (id),
    responsavel_id   bigint        not null references pessoa (id),
    atualizada_por   bigint        not null references pessoa (id),
    atualizada_em    timestamp     not null
);

create index ix_tarefa_area on tarefa (area_id);
create index ix_tarefa_responsavel on tarefa (responsavel_id, status, prazo);
