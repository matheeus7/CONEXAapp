-- Sprint 4.1: Áreas da vida (RF04). Cada Área pertence a uma Minha Vida e nasce privada.
create table area (
    id             bigint generated by default as identity primary key,
    minha_vida_id  bigint       not null references minha_vida (id),
    nome           varchar(80)  not null,
    criada_em      timestamp    not null
);

create index ix_area_minha_vida on area (minha_vida_id);
