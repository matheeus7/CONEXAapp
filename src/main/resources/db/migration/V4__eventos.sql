-- Sprint 4.3: Eventos (RF06). Intervalo [inicio, fim); Área obrigatória.
create table evento (
    id               bigint generated by default as identity primary key,
    area_id          bigint        not null references area (id),
    titulo           varchar(120)  not null,
    inicio           timestamp     not null,
    fim              timestamp     not null,
    atualizada_por   bigint        not null references pessoa (id),
    atualizada_em    timestamp     not null,
    constraint ck_evento_intervalo check (fim > inicio)
);

create index ix_evento_area on evento (area_id);
create index ix_evento_inicio on evento (inicio);
