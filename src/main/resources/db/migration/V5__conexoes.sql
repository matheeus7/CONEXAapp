-- Etapa 5: Conexões (RF08, RF09, RF10). Uma conexão por par (pessoa, Área).
create table conexao (
    id          bigint generated by default as identity primary key,
    area_id     bigint       not null references area (id),
    pessoa_id   bigint       not null references pessoa (id),
    nivel       varchar(12)  not null,
    criada_em   timestamp    not null,
    constraint uk_conexao_area_pessoa unique (area_id, pessoa_id)
);

create index ix_conexao_pessoa on conexao (pessoa_id);
